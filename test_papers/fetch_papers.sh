#!/usr/bin/env bash
# Download the PDFs and the official arXiv BibTeX for every id in arxiv_ids.txt,
# then rebuild references.bib from the official entries.
# Usage: ./fetch_papers.sh   (run from this folder)
set -euo pipefail
cd "$(dirname "$0")"
mkdir -p pdf bib
while read -r id; do
  [ -z "$id" ] && continue
  echo "== $id"
  [ -s "pdf/$id.pdf" ] || curl -fsSL -o "pdf/$id.pdf" "https://arxiv.org/pdf/$id"
  [ -s "bib/$id.bib" ] || curl -fsSL -o "bib/$id.bib" "https://arxiv.org/bibtex/$id"
  sleep 3   # be polite to arXiv
done < arxiv_ids.txt
{
  echo "% Test papers for claim-chain: official arXiv BibTeX, generated by fetch_papers.sh"
  echo
  for id in $(cat arxiv_ids.txt); do cat "bib/$id.bib"; echo; done
} > references.bib
echo "done: $(ls pdf | wc -l) PDFs, $(grep -c '^@' references.bib) BibTeX entries"
