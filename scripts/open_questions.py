"""Collect the open questions of several claim-chain encodings into one catalogue.

An open question is anything an encoding leaves unresolved: a QUESTION statement
that no relation ANSWERS, the open_question of an ASSUMPTION, a LIMITATION or
OUTLOOK statement, or a proof obligation whose status is OPEN. Each entry keeps
the paper and statement it comes from, so that research ideas derived from the
catalogue stay traceable to the papers.

Usage: python scripts/open_questions.py test_papers/yaml/*.yaml -o docs/<dir>/
Writes open_questions.yaml and open_questions.md into the output directory.
"""
import argparse
from collections import Counter
from pathlib import Path

import yaml

KIND_LABEL = {
    "QUESTION": "question",
    "ASSUMPTION": "assumption",
    "LIMITATION": "limitation",
    "OUTLOOK": "outlook",
    "OBLIGATION": "open proof obligation",
}


def collect(chain):
    """Return the open questions of one encoding as a list of dicts."""
    pub = chain.get("publication", {})
    paper = pub.get("arxiv") or pub.get("doi") or pub.get("id")
    answered = {r["object"] for r in chain.get("relations", []) or [] if r.get("predicate") == "ANSWERS"}
    out = []

    def add(kind, sid, text, part):
        out.append({"paper": str(paper), "kind": kind, "source": sid, "paper_part": part, "text": " ".join(str(text).split())})

    for s in chain.get("statements", []) or []:
        t, sid, part = s.get("statement_type"), s.get("id"), s.get("paper_part")
        if t == "QUESTION" and sid not in answered:
            add("QUESTION", sid, s["text"], part)
        elif t == "ASSUMPTION" and s.get("open_question"):
            add("ASSUMPTION", sid, s["open_question"], part)
        elif t in ("LIMITATION", "OUTLOOK"):
            add(t, sid, s["text"], part)
        for po in (s.get("assessment") or {}).get("proof_obligations", []) or []:
            if po.get("obligation_status") == "OPEN":
                add("OBLIGATION", sid, po["text"], part)
    return out


def write_markdown(entries, titles, path):
    lines = ["# Open questions across encodings", "",
             f"{len(entries)} open questions from {len(titles)} encodings, generated by `scripts/open_questions.py`.", "",
             "| Kind | Count |", "|---|---|"]
    for kind, n in Counter(e["kind"] for e in entries).most_common():
        lines.append(f"| {KIND_LABEL[kind]} | {n} |")
    for paper, title in titles.items():
        lines += ["", f"## {paper}: {title}", "", "| Id | Kind | Source | Open question |", "|---|---|---|---|"]
        for e in entries:
            if e["paper"] == paper:
                lines.append(f"| {e['id']} | {KIND_LABEL[e['kind']]} | `{e['source']}` | {e['text'].replace('|', '/')} |")
    path.write_text("\n".join(lines) + "\n")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("encodings", nargs="+", type=Path)
    ap.add_argument("-o", "--out", type=Path, required=True)
    args = ap.parse_args(argv)

    entries, titles = [], {}
    for f in sorted(args.encodings):
        chain = yaml.safe_load(f.read_text())
        found = collect(chain)
        pub = chain.get("publication", {})
        titles[str(pub.get("arxiv") or pub.get("doi") or pub.get("id"))] = pub.get("title", "")
        for i, e in enumerate(found, 1):
            entries.append({"id": f"{e['paper']}:OQ{i}", **e})

    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "open_questions.yaml").write_text(
        yaml.safe_dump({"open_questions": entries}, sort_keys=False, allow_unicode=True, width=1000))
    write_markdown(entries, titles, args.out / "open_questions.md")
    print(f"{len(entries)} open questions from {len(titles)} encodings -> {args.out}")


if __name__ == "__main__":
    main()
